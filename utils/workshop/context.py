"""Private implementation-plan context (spec §2a). Read by the LLM, never rendered."""
import re

_ID_RE = re.compile(r"^[A-Za-z0-9]{15,18}$")
PEOPLE = {"TECHNICAL_CHAMPION", "POC_LED_BY", "IMPLEMENTER"}
NEVER_SENT = {"FUTURE_STATE_DIAGRAM", "EACV", "USE_CASE_NUMBER"}

UC_CONTEXT_SQL = """
SELECT u.SALESFORCE_USE_CASE_ID AS USE_CASE_ID,
  u.SALESFORCE_USE_CASE_DESCRIPTION AS DESCRIPTION, u.SALESFORCE_USE_CASE_TECHNICAL_USE_CASE AS TECHNICAL_USE_CASE,
  u.SALESFORCE_USE_CASE_WORKLOADS AS WORKLOADS, u.SALESFORCE_USE_CASE_INDUSTRY_USE_CASE AS INDUSTRY_USE_CASE,
  u.SALESFORCE_USE_CASE_STAGE AS STAGE, u.SALESFORCE_USE_CASE_STATUS AS STATUS,
  u.SALESFORCE_USE_CASE_DECISION_DATE AS DECISION_DATE, u.SALESFORCE_USE_CASE_GO_LIVE_DATE AS GO_LIVE_DATE,
  u.SALESFORCE_USE_CASE_IMPLEMENTATION_START_DATE AS IMPLEMENTATION_START_DATE,
  u.SALESFORCE_USE_CASE_TECHNICAL_WIN_DATE AS TECHNICAL_WIN_DATE,
  u.SALESFORCE_USE_CASE_SOLUTION_ENGINEER_COMMENTS AS SE_COMMENTS,
  u.SALESFORCE_USE_CASE_PARTNER_COMMENTS AS PARTNER_COMMENTS,
  u.SALESFORCE_USE_CASE_IMPLEMENTATION_COMMENTS AS IMPLEMENTATION_COMMENTS,
  u.SALESFORCE_USE_CASE_SPECIALIST_COMMENTS AS SPECIALIST_COMMENTS,
  u.SALESFORCE_USE_CASE_NEXT_STEPS AS NEXT_STEPS, u.SALESFORCE_USE_CASE_LOSS_DESCRIPTION AS LOSS_DESCRIPTION,
  u.SALESFORCE_USE_CASE_MEDDPICC_IDENTIFY_PAIN AS MEDDPICC_PAIN, u.SALESFORCE_USE_CASE_MEDDPICC_METRICS AS MEDDPICC_METRICS,
  u.SALESFORCE_USE_CASE_MEDDPICC_DECISION_CRITERIA AS MEDDPICC_DECISION_CRITERIA,
  u.SALESFORCE_USE_CASE_MEDDPICC_DECISION_PROCESS AS MEDDPICC_DECISION_PROCESS,
  u.SALESFORCE_USE_CASE_COMPETITORS AS COMPETITORS, u.SALESFORCE_USE_CASE_INCUMBENT_VENDOR AS INCUMBENT_VENDOR,
  u.SALESFORCE_USE_CASE_TECHNICAL_CHAMPION AS TECHNICAL_CHAMPION,
  u.SALESFORCE_USE_CASE_PROOF_OF_CONCEPT_LED_BY AS POC_LED_BY, u.SALESFORCE_USE_CASE_PROOF_OF_CONCEPT_STAGE AS POC_STAGE,
  u.SALESFORCE_USE_CASE_IMPLEMENTER AS IMPLEMENTER, u.IS_SALESFORCE_USE_CASE_MISSION_CRITICAL AS MISSION_CRITICAL,
  u.SALESFORCE_USE_CASE_PROFESSIONAL_SERVICES_ENGAGEMENT AS PS_ENGAGEMENT,
  u.SALESFORCE_USE_CASE_CLOUD_PROVIDER AS CLOUD_PROVIDER, u.SALESFORCE_USE_CASE_CLOUD_REGION AS CLOUD_REGION,
  u.SALESFORCE_USE_CASE_LINE_OF_BUSINESS AS LINE_OF_BUSINESS,
  u.SALESFORCE_USE_CASE_RISK_DESCRIPTION AS RISK_DESCRIPTION,
  u.SALESFORCE_USE_CASE_FUTURE_STATE_ARCHITECTURE_DIAGRAM AS FUTURE_STATE_DIAGRAM,
  a.SALESFORCE_ACCOUNT_INDUSTRY AS INDUSTRY, a.SALESFORCE_ACCOUNT_SUBINDUSTRY AS SUB_INDUSTRY,
  a.SALESFORCE_ACCOUNT_BILLING_COUNTRY AS BILLING_COUNTRY, a.SALESFORCE_ACCOUNT_BILLING_STATE AS BILLING_STATE,
  a.SALESFORCE_ACCOUNT_WEBSITE AS WEBSITE, a.SALESFORCE_ACCOUNT_NUMBER_OF_EMPLOYEES AS EMPLOYEES,
  a.SALESFORCE_ACCOUNT_TYPE AS ACCOUNT_TYPE, a.SALESFORCE_ACCOUNT_SEGMENT AS SEGMENT
FROM SNOW_CERTIFIED.SALESFORCE_USE_CASE.DD_SALESFORCE_USE_CASE u
LEFT JOIN SNOW_CERTIFIED.SALESFORCE_ACCOUNT.DD_SALESFORCE_ACCOUNT a
  ON a.SALESFORCE_ACCOUNT_ID = u.SALESFORCE_ACCOUNT_ID
WHERE u.SALESFORCE_USE_CASE_ID IN ({ids})
"""


def fetch_uc_context(conn, uc_ids: list) -> dict:
    safe = [i for i in uc_ids if i and _ID_RE.match(i)]
    if not safe:
        return {}
    df = conn.query(UC_CONTEXT_SQL.format(ids=", ".join(f"'{i}'" for i in safe)), ttl=3600)
    out = {}
    for _, r in df.iterrows():
        d = {}
        for k, v in r.items():
            if k in NEVER_SENT or k == "USE_CASE_ID" or v is None or str(v).strip() in ("", "nan", "None"):
                continue
            d[k] = "named champion identified" if k in PEOPLE else str(v)
        out[r["USE_CASE_ID"]] = d
    return out
